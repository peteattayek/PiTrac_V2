"""Copy named functions out of firmware sources, verbatim, into one file a test includes.

Some guards live inside files a host test cannot link whole: `reset` and `bootsel`
in cli.c (the whole SDK), `cfg save`'s guard in config_store.c (flash). The test
build copies those functions unchanged, so a change to them in src/ changes what
the test runs. Added for image 1.10 (review finding V19-F1, 2026-11-12), the way
extract_cli_gpio.py copies the `gpio` command for engine_test, and the way the
1.9 independent review's probe copied these same guards.

A function is matched from its definition line -- at column 0, optionally
`static`, its whole parameter list on that line, ending in ` {` -- to the first
`}` at column 0. Every name must match exactly once.

usage: extract_functions.py <output.c> <source.c> <name>[,<name>...] [<source.c> <names> ...]
"""
import os
import re
import sys


def main():
    args = sys.argv[1:]
    if len(args) < 3 or len(args) % 2 != 1:
        sys.exit(__doc__)
    out = args[0]
    parts = ['/* GENERATED by tests/extract_functions.py -- do not edit. */']
    for src, names in zip(args[1::2], args[2::2]):
        text = open(src, encoding='utf-8').read().replace('\r\n', '\n')
        parts.append('/* from src/%s */' % os.path.basename(src))
        for name in names.split(','):
            pat = r'^(?:static )?[^\n(]*\b' + re.escape(name) + r'\([^\n]*\) \{\n.*?^\}'
            found = re.findall(pat, text, re.M | re.S)
            if len(found) != 1:
                sys.exit(f'extract_functions.py: {name}() found {len(found)} times in {src}')
            parts.append(found[0])
    open(out, 'w', encoding='utf-8', newline='\n').write('\n\n'.join(parts) + '\n')


main()

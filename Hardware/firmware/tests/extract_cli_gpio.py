"""Copy the `gpio` command out of src/cli.c, verbatim, for tests/engine_test.c.

cli.c as a whole needs the whole SDK; its `gpio` command needs only the argument
parsers and the GPIO / camera calls. So the test build copies those functions
unchanged into one file the test includes, and the test runs the real command
against the real camera.c (independent review 2026-11-10, H7-F3: `gpio 10 1`
drove the camera trigger with the rail down). Copied, not rewritten: a change to
the command in cli.c changes what the test runs.

usage: extract_cli_gpio.py <cli.c> <output.c>
"""
import re
import sys

FUNCTIONS = ['parse_u32', 'parse_u32_in', 'bad_arg', 'gpio_writable', 'cmd_gpio']


def main():
    src, out = sys.argv[1], sys.argv[2]
    text = open(src, encoding='utf-8').read().replace('\r\n', '\n')
    parts = ['/* GENERATED by tests/extract_cli_gpio.py from src/cli.c -- do not edit. */']
    for name in FUNCTIONS:
        m = re.search(r'^static [^\n]*\b' + name + r'\([^\n]*\) \{.*?^\}', text, re.M | re.S)
        if not m:
            sys.exit(f'extract_cli_gpio.py: {name}() not found in {src}')
        parts.append(m.group(0))
    open(out, 'w', encoding='utf-8', newline='\n').write('\n\n'.join(parts) + '\n')


main()

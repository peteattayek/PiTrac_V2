strobe_refusal_t strobe_live_arm(void) {
    if (s_live) { s_live_touch_ms = now_ms(); return STROBE_OK; }
    strobe_snapshot_t snap = snapshot();
    strobe_live_t l = live_inputs(false, 0.0f);
    strobe_refusal_t r = strobe_live_may_arm(&snap, &l);
    if (r != STROBE_OK) return r;

    // A hang with current flowing is the risk the watchdog is for (service.h).
    // If the operator had already armed it, it stays theirs.
    s_live_owns_wdog = !pitrac_watchdog_enabled();
    if (s_live_owns_wdog) pitrac_watchdog_enable(true);

    s_live          = true;
    s_live_since_ms = s_live_touch_ms = now_ms();
    s_live_proven   = 0;                 // the staircase starts again from zero
    memset(&s_shot, 0, sizeof(s_shot));
    s_wave_n        = 0;
    return STROBE_OK;
}

void strobe_live_disarm(void) { live_exit(STROBE_LIVE_EXIT_OPERATOR, STROBE_OK); }

bool strobe_live_armed(void) { return s_live; }

void strobe_live_keep_watchdog(void) { s_live_owns_wdog = false; }

void strobe_live_service(void) {
    if (!s_live || s_live_firing || s_busy) return;
    strobe_snapshot_t snap = snapshot();
    strobe_live_t l = live_inputs(false, 0.0f);
    strobe_refusal_t r = strobe_live_may_continue(&snap, &l);
    if (r != STROBE_OK) {
        live_exit(STROBE_LIVE_EXIT_CONDITION, r);
        return;
    }
    if (strobe_live_idle_expired(now_ms(), s_live_touch_ms))
        live_exit(STROBE_LIVE_EXIT_IDLE, STROBE_OK);
}

const strobe_live_shot_t *strobe_live_last(void) { return &s_shot; }

size_t strobe_live_wave(const uint16_t **samples) {
    if (samples) *samples = s_wave;
    return s_wave_n;
}

const char *strobe_live_exit_text(strobe_live_exit_t e) {
    switch (e) {
        case STROBE_LIVE_EXIT_NONE:        return "not armed since boot";
        case STROBE_LIVE_EXIT_OPERATOR:    return "strobe live off";
        case STROBE_LIVE_EXIT_SAFE_OFF:    return "strobe off, or the rail went down";
        case STROBE_LIVE_EXIT_CONDITION:   return "a hold condition failed";
        case STROBE_LIVE_EXIT_IDLE:        return "idle timeout";
        case STROBE_LIVE_EXIT_OVERCURRENT: return "OVERCURRENT -- fault latched";
        case STROBE_LIVE_EXIT_CLAMP:       return "CURRENT OUTSIDE THE PULSE -- fault latched";
        case STROBE_LIVE_EXIT_READBACK:    return "ADC0 readback unusable";
        case STROBE_LIVE_EXIT_RUN:         return "a firing timed out or was aborted";
    }
    return "?";
}


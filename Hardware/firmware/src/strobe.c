// Validate and encode. false = INVALID, with r filled in.
static bool prepare(const strobe_burst_t *b, uint32_t max_width_us, bool live,
                    strobe_result_t *r, size_t *n_words) {
    memset(r, 0, sizeof(*r));
    r->valid        = true;
    r->live         = live;
    if (b) r->burst = *b;          // NULL falls through to INVALID below; the plan
                                   // helpers are NULL-safe, this copy was not
    r->max_width_us = max_width_us;
    r->expected_us  = strobe_burst_duration_us(b);
    r->gate_level   = s_gate_level;

    r->burst_err = live ? strobe_validate_live_burst(b, max_width_us)
                        : strobe_validate_burst(b, max_width_us);
    size_t n = 0;
    if (r->burst_err == STROBE_BURST_OK) n = strobe_encode(b, s_words, count_of(s_words));
    if (r->burst_err != STROBE_BURST_OK || n == 0) {
        r->outcome = STROBE_RUN_INVALID;
        return false;
    }
    r->words  = (uint32_t)n;
    *n_words  = n;
    return true;
}

// Run an admitted, encoded burst and wait for IRQ0 while servicing the FSM.
// *t_enable is when the state machine was enabled.
static void engine_fire(strobe_result_t *r, size_t n_words, uint64_t *t_enable) {
    PIO pio = STROBE_PIO;
    uint sm = STROBE_SM;
    const uint32_t pin_mask = 1u << PIN_STROBE_PULSE;

    // Known state, then the PIO's own output latch low and enabled while the pad
    // is still SIO low. Only then does the pad change hands.
    engine_reset();
    pio_sm_exec(pio, sm, pio_encode_jmp(s_offset));
    pio_sm_set_pins_with_mask(pio, sm, 0u, pin_mask);
    pio_sm_set_pindirs_with_mask(pio, sm, pin_mask, pin_mask);

    dma_channel_config c = dma_channel_get_default_config((uint)s_dma);
    channel_config_set_transfer_data_size(&c, DMA_SIZE_32);
    channel_config_set_read_increment(&c, true);
    channel_config_set_write_increment(&c, false);
    channel_config_set_dreq(&c, pio_get_dreq(pio, sm, true));
    dma_channel_configure((uint)s_dma, &c, &pio->txf[sm], s_words, (uint)n_words, true);

    const uint32_t gen = s_run_gen;
    s_busy = true;
    pio_gpio_init(pio, PIN_STROBE_PULSE);
    uint64_t t0 = time_us_64();
    pio_sm_set_enabled(pio, sm, true);

    const uint64_t limit = (uint64_t)r->expected_us + STROBE_TIMEOUT_MARGIN_US;
    r->outcome = STROBE_RUN_TIMEOUT;
    for (;;) {
        if (pio_interrupt_get(pio, STROBE_IRQ)) {
            r->irq_seen = true;
            r->outcome  = STROBE_RUN_OK;
            break;
        }
        if (time_us_64() - t0 > limit) break;

        // Keep the FSM, the supply monitor and the button escape hatch alive.
        // If they tear the rail down, strobe_safe_off() has already run.
        yield_t y = pitrac_service();
        if (s_run_gen != gen || !s_busy || !power_rails_ready())
                                                 { r->outcome = STROBE_RUN_ABORT_POWER; break; }
        if (y == YIELD_ABORT_FAULT || fault_current() != FAULT_NONE)
                                                 { r->outcome = STROBE_RUN_ABORT_FAULT; break; }
        if (y == YIELD_ABORT_KEY)                { r->outcome = STROBE_RUN_ABORT_KEY;   break; }
    }
    r->observed_us = (uint32_t)(time_us_64() - t0);

    engine_reset();
    if (s_run_gen != gen) r->outcome = STROBE_RUN_ABORT_POWER;
    r->pin_low_after = !gpio_get(PIN_STROBE_PULSE);
    if (t_enable) *t_enable = t0;
}

static strobe_result_t run_dry(const strobe_burst_t *b, uint32_t max_width_us) {
    strobe_result_t r;
    size_t n = 0;
    if (!prepare(b, max_width_us, false, &r, &n)) { s_last = r; return r; }

    strobe_snapshot_t snap = snapshot();
    r.refusal = strobe_may_fire(&snap);
    if (r.refusal != STROBE_OK) {
        r.outcome = STROBE_RUN_REFUSED;
        s_last = r;
        return r;
    }
    engine_fire(&r, n, NULL);
    s_last = r;
    return r;
}

// 6d: a clamp test while live only at the level of the most recent live firing,
// and only if that firing measured STROBE_6D_MIN_A..STROBE_6D_MAX_A.
static bool clamptest_level_ok(void) {
    return s_shot.valid && s_shot.gate_level == s_gate_level
        && s_shot.meas.verdict == STROBE_VERDICT_OK && s_shot.meas.detected
        && s_shot.meas.max_amps >= STROBE_6D_MIN_A
        && s_shot.meas.max_amps <= STROBE_6D_MAX_A;
}

static strobe_result_t run_live(const strobe_burst_t *b, uint32_t max_width_us) {
    strobe_result_t r;
    size_t n = 0;
    s_live_touch_ms = now_ms();
    if (!prepare(b, max_width_us, true, &r, &n)) { s_last = r; return r; }

    const bool clamptest = max_width_us > (uint32_t)STROBE_SW_MAX_US;
    r.booked_mc = strobe_burst_charge_mc(b->width_us, b->count);
    strobe_snapshot_t snap = snapshot();
    strobe_live_t l = live_inputs(true, r.booked_mc);
    r.refusal = strobe_live_may_fire(&snap, &l);
    if (r.refusal == STROBE_OK && clamptest && !clamptest_level_ok()) r.refusal = STROBE_REFUSE_6D;
    if (r.refusal != STROBE_OK) {
        r.outcome = STROBE_RUN_REFUSED;
        s_last = r;
        return r;
    }

    // Booked before firing, so an aborted firing still counts.
    strobe_budget_book(&s_budget, now_ms(), r.booked_mc);
    s_live_firing = true;

    // ADC0 alone at 500 ksps, with a baseline before the first edge. This
    // destroys the IDLE ring's history, which nothing needs here: live mode
    // requires the detector disarmed.
    adc_engine_set_mode(ADC_MODE_BURST);
    busy_wait_us(STROBE_LIVE_PRE_US);

    uint64_t t_en = 0;
    engine_fire(&r, n, &t_en);
    s_live_last_fire_us = t_en ? t_en : 1u;

    busy_wait_us(STROBE_LIVE_POST_US);

    // The window starts (PRE - 40) us before the enable -- 40 us inside the BURST
    // run, so every sample is ch0 -- and ends at the freeze. The baseline/pulse
    // split is counted back from the freeze's own stop instant, read with
    // interrupts off (review 2026-10-07): a clock read here, before the freeze,
    // could be separated from the stop by an interrupt of any length.
    const uint64_t since = t_en - (uint64_t)(STROBE_LIVE_PRE_US - 40u);
    uint64_t t_stop = 0;
    bool err = false;
    size_t got = adc_ring_freeze_copy(ADC_CH_CURRENT, since, s_wave,
                                      STROBE_LIVE_WAVE_MAX_SAMPLES, &err, &t_stop);
    adc_engine_set_mode(ADC_MODE_IDLE);
    s_wave_n = got;
    r.readback_err = err;
    size_t pre = strobe_live_baseline_samples(got, t_en, t_stop);

    memset(&s_shot, 0, sizeof(s_shot));
    s_shot.valid        = true;
    s_shot.gate_level   = r.gate_level;
    s_shot.burst        = r.burst;
    s_shot.readback_err = err;
    strobe_live_measure(s_wave, got, pre, r.burst.count, &s_shot.meas);
    s_live_firing = false;
    s_last = r;

    // Most severe first. Each one that ends live mode leaves the gate at 0. A
    // run the power FSM aborted has already been dropped as SAFE_OFF, and the
    // live_exit() calls below keep that reason.
    const strobe_verdict_t v = s_shot.meas.verdict;
    if (v == STROBE_VERDICT_STUCK_ON) {
        fault_raise(FAULT_STROBE_CLAMP);
        live_exit(STROBE_LIVE_EXIT_CLAMP, STROBE_OK);
    } else if (v == STROBE_VERDICT_OVERCURRENT) {
        fault_raise(FAULT_STROBE_OVERCURRENT);
        live_exit(STROBE_LIVE_EXIT_OVERCURRENT, STROBE_OK);
    } else if (r.outcome != STROBE_RUN_OK) {
        live_exit(STROBE_LIVE_EXIT_RUN, STROBE_OK);
    } else if (err || v != STROBE_VERDICT_OK) {
        live_exit(STROBE_LIVE_EXIT_READBACK, STROBE_OK);
    } else if (r.gate_level > s_live_proven) {
        s_live_proven = r.gate_level;
    }
    return r;
}

strobe_result_t strobe_run(const strobe_burst_t *b, uint32_t max_width_us) {
    return s_live ? run_live(b, max_width_us) : run_dry(b, max_width_us);
}

const char *strobe_run_text(strobe_run_t r) {
    switch (r) {
        case STROBE_RUN_OK:          return "completed, IRQ0 seen";
        case STROBE_RUN_INVALID:     return "INVALID burst -- nothing fired";
        case STROBE_RUN_REFUSED:     return "REFUSED -- nothing fired";
        case STROBE_RUN_TIMEOUT:     return "TIMEOUT -- IRQ0 never seen; engine stopped";
        case STROBE_RUN_ABORT_POWER: return "ABORTED -- rail went down or the strobe was torn down mid-burst";
        case STROBE_RUN_ABORT_FAULT: return "ABORTED -- a fault was raised mid-burst";
        case STROBE_RUN_ABORT_KEY:   return "ABORTED -- key pressed";
    }
    return "?";
}


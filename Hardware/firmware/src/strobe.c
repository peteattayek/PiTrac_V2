void strobe_init(void) {
    // A7: GPIO12 and GPIO28 are the SAME PWM channel (slice 6A). The ready LED
    // must have given the slice up before the gate DAC claims it, or LED
    // brightness becomes the current setpoint.
    hard_assert(gpio_get_function(PIN_READY_LED) != GPIO_FUNC_PWM);

    // Gate DAC: compare 0 before the pad is handed to PWM, so it never glitches.
    s_gate_slice = pwm_gpio_to_slice_num(PIN_GATE_PWM);
    s_gate_chan  = pwm_gpio_to_channel(PIN_GATE_PWM);
    pwm_config c = pwm_get_default_config();
    pwm_config_set_wrap(&c, (uint16_t)DAC_TOP);
    pwm_config_set_clkdiv_int(&c, 1);          // 150 MHz / 1024 = 146.48 kHz
    pwm_init(s_gate_slice, &c, false);
    pwm_set_chan_level(s_gate_slice, s_gate_chan, 0);
    pwm_set_enabled(s_gate_slice, true);
    gpio_set_function(PIN_GATE_PWM, GPIO_FUNC_PWM);
    s_gate_level = 0;

    // Burst engine. pio_alloc_init() set PIO0's GPIOBASE to 0, so GPIO25 is in
    // range; the program leaves the pad alone until a burst is admitted.
    //
    // No partial-init teardown is needed (audit STR-02, checked 2026-10-07):
    // pio_sm_claim(), pio_add_program() and dma_claim_unused_channel(true) all
    // panic on failure, so this function either completes or never returns, and
    // strobe_safe_off() drives GPIO25 low before it looks at s_inited.
    hard_assert(pio_get_gpio_base(STROBE_PIO) == PIO_BASE_LOW);
    pio_sm_claim(STROBE_PIO, STROBE_SM);
    s_offset = pio_add_program(STROBE_PIO, &strobe_burst_program);
    strobe_burst_program_init(STROBE_PIO, STROBE_SM, s_offset, PIN_STROBE_PULSE);
    s_dma = dma_claim_unused_channel(true);

    engine_reset();
    s_inited = true;
}

// Leave live mode: the flags and the watchdog only. The caller owns the hardware.
static void live_drop(strobe_live_exit_t why, strobe_refusal_t r) {
    if (!s_live) return;
    s_live = false;
    s_live_exit = why;
    s_live_exit_refusal = r;
    if (s_live_owns_wdog) pitrac_watchdog_enable(false);
    s_live_owns_wdog = false;
}

void strobe_safe_off(void) {
    pulse_pin_sio_low();
    s_run_gen++;
    live_drop(STROBE_LIVE_EXIT_SAFE_OFF, STROBE_OK);
    if (!s_inited) return;
    engine_reset();
    // Non-blocking on purpose: the power FSM calls this. The decay window is
    // enforced at the next admission instead (strobe_gate_settling()).
    gate_write(0);
}

// Leave live mode for a stated reason, with everything safe. live_drop() first,
// so the reason recorded is this one and not strobe_safe_off()'s generic one.
static void live_exit(strobe_live_exit_t why, strobe_refusal_t r) {
    live_drop(why, r);
    strobe_safe_off();
}


strobe_refusal_t strobe_gate_set(uint16_t level) {
    if (level > DAC_TOP + 1u) level = (uint16_t)(DAC_TOP + 1u);

    strobe_snapshot_t snap = snapshot();
    strobe_refusal_t r;
    if (s_live) {
        s_live_touch_ms = now_ms();
        strobe_live_t l = live_inputs(false, 0.0f);
        r = strobe_live_may_set_gate(&snap, &l, level);
    } else {
        r = strobe_may_set_gate(&snap, level);
    }
    if (r != STROBE_OK) return r;
    if (!s_inited) return level == 0u ? STROBE_OK : STROBE_REFUSE_BUSY;

    gate_write(level);
    gpio_set_function(PIN_GATE_PWM, GPIO_FUNC_PWM);

    // The 2-pole RC ladder's dominant pole is 2.62 ms. The FSM keeps running;
    // if the rail drops meanwhile, strobe_safe_off() has already zeroed it.
    pitrac_yield_ms(DAC_SETTLE_MS);
    return STROBE_OK;
}

uint16_t strobe_gate_level(void) { return s_gate_level; }


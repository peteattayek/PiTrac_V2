void strobe_info(strobe_info_t *o) {
    o->inited          = s_inited;
    o->busy            = s_busy;
    o->gate_level      = s_gate_level;
    o->gate_hw_level   = s_inited ? gate_hw_level() : 0u;
    o->gate_pin_pwm    = gpio_get_function(PIN_GATE_PWM) == GPIO_FUNC_PWM;
    o->gate_settling   = s_inited && strobe_gate_settling(time_us_64(), s_gate_zeroed_us);
    o->pulse_pin_pio   = gpio_get_function(PIN_STROBE_PULSE) == GPIO_FUNC_PIO0;
    o->pulse_pin_pad   = gpio_get(PIN_STROBE_PULSE);
    o->ready_led_sio   = gpio_get_function(PIN_READY_LED) == GPIO_FUNC_SIO;
    o->limit_out_sio   = gpio_get_function(PIN_PULSE_LIMIT_DIS) == GPIO_FUNC_SIO
                      && gpio_is_dir_out(PIN_PULSE_LIMIT_DIS);
    o->limit_out_level = gpio_get_out_level(PIN_PULSE_LIMIT_DIS);
    o->limit_pad       = gpio_get(PIN_PULSE_LIMIT_DIS);
    o->pio_offset      = s_offset;
    o->dma_channel     = s_dma;
    o->snap            = snapshot();
    o->last            = s_last;

    uint32_t t = now_ms();
    o->live              = s_live;
    o->live_owns_wdog    = s_live_owns_wdog;
    o->live_in           = live_inputs(true, strobe_burst_charge_mc(STROBE_CAL_WIDTH_US, 1u));
    o->live_for_ms       = s_live ? (uint32_t)(t - s_live_since_ms) : 0u;
    uint32_t idle        = (uint32_t)(t - s_live_touch_ms);
    o->idle_left_ms      = (s_live && idle < STROBE_LIVE_IDLE_TIMEOUT_MS)
                         ? STROBE_LIVE_IDLE_TIMEOUT_MS - idle : 0u;
    o->budget_used_mc    = strobe_budget_used_mc(&s_budget, t);
    o->live_exit         = s_live_exit;
    o->live_exit_refusal = s_live_exit_refusal;
}

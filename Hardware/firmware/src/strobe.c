#define STROBE_PIO  PIO_BLK_LOW
#define STROBE_SM   PIO_SM_STROBE
#define STROBE_IRQ  0u

static bool            s_inited;
static bool            s_busy;
static uint            s_offset;
static int             s_dma = -1;
static uint            s_gate_slice, s_gate_chan;
static uint16_t        s_gate_level;
static uint64_t        s_gate_zeroed_us;   // last non-zero -> zero transition; 0 = never
static uint32_t        s_words[2u * STROBE_BURST_MAX_PULSES + 1u];
static strobe_result_t s_last;

// Bumped by every strobe_safe_off(). A firing notes it before enabling the
// engine, and if it has moved by the end, something tore the strobe down
// mid-firing: the run is an abort whatever else looks fine (audit STR-04/05).
static uint32_t        s_run_gen;

// --- Live mode ---------------------------------------------------------------
static bool               s_live;
static bool               s_live_firing;      // a live firing is in progress: the hook stays out
static bool               s_live_owns_wdog;   // we armed the watchdog, so we disarm it
static strobe_live_exit_t s_live_exit = STROBE_LIVE_EXIT_NONE;
static strobe_refusal_t   s_live_exit_refusal;
static uint32_t           s_live_since_ms;
static uint32_t           s_live_touch_ms;    // last strobe command, for the idle timeout
static uint16_t           s_live_proven;      // the staircase: highest level fired and judged OK

// Deliberately NOT reset by arming: `strobe live off` then `on` must not buy a
// fresh charge budget or skip the firing interval.
static uint64_t           s_live_last_fire_us; // 0 = never
static strobe_budget_t    s_budget;

static strobe_live_shot_t s_shot;
static uint16_t           s_wave[STROBE_LIVE_WAVE_MAX_SAMPLES];
static size_t             s_wave_n;

static strobe_cal_point_t s_cal_pts[STROBE_CAL_MAX_POINTS];
static size_t             s_cal_n;
static strobe_cal_t       s_cal;

static uint32_t now_ms(void) { return to_ms_since_boot(get_absolute_time()); }

// ---------------------------------------------------------------------------
// Pin ownership.
//
// GPIO25 is SIO driven low except while an admitted burst runs, and every exit
// path puts it back BEFORE touching the state machine. gpio_set_function() hands
// the pad over immediately, so the SIO output level and direction are written
// first: the pad never sees anything but low during the switch. R57 1K is the
// backstop if the pad ever floats.
// ---------------------------------------------------------------------------
static void pulse_pin_sio_low(void) {
    gpio_put(PIN_STROBE_PULSE, 0);
    gpio_set_dir(PIN_STROBE_PULSE, GPIO_OUT);
    gpio_set_function(PIN_STROBE_PULSE, GPIO_FUNC_SIO);
}

static void engine_reset(void) {
    pulse_pin_sio_low();
    pio_sm_set_enabled(STROBE_PIO, STROBE_SM, false);
    if (s_dma >= 0) dma_channel_abort((uint)s_dma);
    pio_sm_clear_fifos(STROBE_PIO, STROBE_SM);
    pio_sm_restart(STROBE_PIO, STROBE_SM);
    pio_interrupt_clear(STROBE_PIO, STROBE_IRQ);
    s_busy = false;
}

static uint16_t gate_hw_level(void) {
    uint32_t cc = pwm_hw->slice[s_gate_slice].cc;
    return (uint16_t)(s_gate_chan ? (cc >> 16) : (cc & 0xFFFFu));
}

// The one place the gate DAC level is written. Lowering from any non-zero level
// starts the decay window that strobe_gate_settling() enforces.
static void gate_write(uint16_t level) {
    bool was_nonzero = s_gate_level != 0u || gate_hw_level() != 0u;
    pwm_set_chan_level(s_gate_slice, s_gate_chan, level);
    s_gate_level = level;
    if (level == 0u && was_nonzero) {
        uint64_t now = time_us_64();
        s_gate_zeroed_us = now ? now : 1u;    // 0 is reserved for "never"
    }
}

// "Provably zero", from the hardware as well as the commanded value, and long
// enough ago that the analog chain has decayed. Anything that cannot be vouched
// for counts as non-zero.
static bool gate_output_nonzero(void) {
    if (s_gate_level != 0u) return true;
    if (strobe_gate_settling(time_us_64(), s_gate_zeroed_us)) return true;
    gpio_function_t f = gpio_get_function(PIN_GATE_PWM);
    if (f == GPIO_FUNC_PWM) return gate_hw_level() != 0u;
    if (f == GPIO_FUNC_SIO) return !gpio_is_dir_out(PIN_GATE_PWM) || gpio_get_out_level(PIN_GATE_PWM);
    return true;
}

// Live firings need the hardware to be exactly what was commanded.
static bool gate_hw_matches(void) {
    return s_inited && gpio_get_function(PIN_GATE_PWM) == GPIO_FUNC_PWM
        && gate_hw_level() == s_gate_level;
}

// Read only. GPIO27 is written in exactly one place, safe_state_init().
static bool pulse_limit_defeated(void) {
    return gpio_get_function(PIN_PULSE_LIMIT_DIS) != GPIO_FUNC_SIO
        || !gpio_is_dir_out(PIN_PULSE_LIMIT_DIS)
        || gpio_get_out_level(PIN_PULSE_LIMIT_DIS)
        || gpio_get(PIN_PULSE_LIMIT_DIS);
}

static strobe_snapshot_t snapshot(void) {
    strobe_snapshot_t s;
    s.rails_ready          = power_rails_ready();
    s.fault_latched        = fault_current() != FAULT_NONE;
    s.pi_present           = power_pi_present();
    s.pulse_limit_defeated = pulse_limit_defeated();
    s.ready_led_on_pwm     = gpio_get_function(PIN_READY_LED) == GPIO_FUNC_PWM;
    // Not initialised: nothing can be vouched for, so behave as busy/non-zero.
    s.engine_busy          = s_busy || !s_inited;
    // The pad itself, not inferred from s_busy (audit STR-07). The policy checks
    // busy first, so a pad that is high DURING a burst still reads as busy.
    s.pulse_pin_high       = gpio_get(PIN_STROBE_PULSE);
    s.gate_nonzero         = !s_inited || gate_output_nonzero();
    return s;
}

// The live policy's inputs. `pacing` adds the interval and the budget for a
// firing of `booking_mc`; without it they read as satisfied, because only a
// firing is gated on them.
static strobe_live_t live_inputs(bool pacing, float booking_mc) {
    strobe_live_t l;
    l.live           = s_live;
    l.watchdog_armed = pitrac_watchdog_enabled();
    l.beam_on        = beam_enabled();
    l.detect_armed   = detect_armed();
    l.adc_idle       = adc_engine_mode() == ADC_MODE_IDLE && adc_ring_running();
    l.gate_hw_match  = gate_hw_matches();
    l.gate_level     = s_gate_level;
    l.gate_proven    = s_live_proven;
    l.interval_ok    = !pacing || strobe_live_interval_ok(time_us_64(), s_live_last_fire_us);
    l.budget_ok      = !pacing || strobe_budget_admits(&s_budget, now_ms(), booking_mc);
    return l;
}


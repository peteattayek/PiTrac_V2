// Wait until a live firing of `mc` would be admitted on pacing, servicing the
// FSM. false if live mode dropped, an abort arrived, or it would take longer
// than a whole budget window (something else is wrong).
static bool wait_for_pacing(float mc) {
    uint32_t t0 = now_ms();
    for (;;) {
        if (!s_live) return false;
        if (strobe_live_interval_ok(time_us_64(), s_live_last_fire_us) &&
            strobe_budget_admits(&s_budget, now_ms(), mc)) return true;
        if ((uint32_t)(now_ms() - t0) > STROBE_LIVE_BUDGET_WINDOW_MS + 1000u) return false;
        if (pitrac_yield_ms(5) != YIELD_OK) return false;
        s_live_touch_ms = now_ms();
    }
}

// One 20 us pulse at the current level. false if it did not complete with a
// usable verdict; *c says why.
static bool cal_fire(strobe_cal_t *c, strobe_cal_point_t *p) {
    static const strobe_burst_t pulse = { STROBE_CAL_WIDTH_US, 0u, 1u };
    if (!wait_for_pacing(strobe_burst_charge_mc(pulse.width_us, pulse.count))) {
        c->res = s_live ? STROBE_CAL_RES_ABORTED : STROBE_CAL_RES_LIVE_LOST;
        return false;
    }
    strobe_result_t r = strobe_run(&pulse, (uint32_t)STROBE_SW_MAX_US);
    if (r.outcome == STROBE_RUN_REFUSED || r.outcome == STROBE_RUN_INVALID) {
        c->res = STROBE_CAL_RES_REFUSED;
        c->refusal = r.refusal;
        return false;
    }
    if (!s_live) { c->res = STROBE_CAL_RES_LIVE_LOST; return false; }
    if (r.outcome != STROBE_RUN_OK) { c->res = STROBE_CAL_RES_ABORTED; return false; }
    p->level    = r.gate_level;
    p->detected = s_shot.meas.detected;
    p->amps     = p->detected ? s_shot.meas.max_amps : 0.0f;
    return true;
}

strobe_cal_t strobe_cal(float target_a, strobe_cal_report_fn report) {
    strobe_cal_t c;
    memset(&c, 0, sizeof(c));
    c.valid    = true;
    c.target_a = target_a;
    s_cal_n    = 0;

    if (!s_live) {
        c.res = STROBE_CAL_RES_REFUSED;
        c.refusal = STROBE_REFUSE_NOT_LIVE;
        s_cal = c;
        return c;
    }

    // From zero, wherever the gate was. Level 0 is always admitted.
    (void)strobe_gate_set(0);
    strobe_refusal_t g;
    uint16_t prev_level = 0;
    float    prev_amps  = 0.0f;
    bool     solved     = false;

    for (;;) {
        if (s_cal_n >= STROBE_CAL_MAX_POINTS) { c.res = STROBE_CAL_RES_TOO_MANY; break; }
        if (pitrac_abort_pending()) { c.res = STROBE_CAL_RES_ABORTED; break; }

        strobe_cal_point_t p;
        if (!cal_fire(&c, &p)) break;
        s_cal_pts[s_cal_n++] = p;
        if (report) report(&p, false);

        uint16_t next = p.level;
        strobe_cal_step_t st = strobe_cal_next(p.level, p.amps, p.detected, target_a, &next);
        if (st == STROBE_CAL_SOLVED) {
            c.solved_level = strobe_cal_solve(prev_level, prev_amps, p.level, p.amps, target_a);
            solved = true;
            break;
        }
        if (st == STROBE_CAL_OVERSHOOT) { c.res = STROBE_CAL_RES_OVERSHOOT; break; }
        if (st == STROBE_CAL_CEILING)   { c.res = STROBE_CAL_RES_CEILING;   break; }

        prev_level = p.level;
        prev_amps  = p.amps;
        g = strobe_gate_set(next);
        if (g != STROBE_OK) { c.res = STROBE_CAL_RES_REFUSED; c.refusal = g; break; }
    }

    if (solved) {
        // At or below the level that bracketed the target, so it was proven.
        g = strobe_gate_set(c.solved_level);
        if (g != STROBE_OK) {
            c.res = STROBE_CAL_RES_REFUSED;
            c.refusal = g;
            solved = false;
        }
    }
    if (solved) {
        float sum = 0.0f;
        bool ok = true;
        for (uint32_t k = 0; k < STROBE_CAL_CONFIRM_PULSES; k++) {
            if (pitrac_abort_pending()) { c.res = STROBE_CAL_RES_ABORTED; ok = false; break; }
            strobe_cal_point_t p;
            if (!cal_fire(&c, &p)) { ok = false; break; }
            if (report) report(&p, true);
            c.confirm_a[c.n_confirm++] = p.amps;
            sum += p.amps;
        }
        if (ok) {
            c.res = STROBE_CAL_RES_SOLVED;
            c.confirm_mean_a = sum / (float)c.n_confirm;
            c.confirm_ok = true;
            for (uint32_t k = 0; k < c.n_confirm; k++) {
                float e = (c.confirm_a[k] - target_a) / target_a;
                if (e > STROBE_CAL_CONFIRM_TOL || e < -STROBE_CAL_CONFIRM_TOL) c.confirm_ok = false;
            }
        }
    }

    // Anything but a solution leaves the gate at zero (and still live, if it is).
    if (c.res != STROBE_CAL_RES_SOLVED && s_live) (void)strobe_gate_set(0);
    s_cal = c;
    return c;
}

size_t strobe_cal_points(const strobe_cal_point_t **pts) {
    if (pts) *pts = s_cal_pts;
    return s_cal_n;
}

const strobe_cal_t *strobe_cal_last(void) { return &s_cal; }

const char *strobe_cal_res_text(strobe_cal_res_t r) {
    switch (r) {
        case STROBE_CAL_RES_SOLVED:    return "solved";
        case STROBE_CAL_RES_REFUSED:   return "REFUSED";
        case STROBE_CAL_RES_OVERSHOOT: return "OVERSHOOT -- a step measured over 1.2 x the target";
        case STROBE_CAL_RES_CEILING:   return "CEILING -- the live gate ceiling was reached below the target";
        case STROBE_CAL_RES_LIVE_LOST: return "LIVE MODE DROPPED mid-cal";
        case STROBE_CAL_RES_ABORTED:   return "ABORTED";
        case STROBE_CAL_RES_TOO_MANY:  return "too many steps without an answer";
    }
    return "?";
}

